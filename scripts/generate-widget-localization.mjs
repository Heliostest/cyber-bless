import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { APP_HIDDEN_SCENE_IDS, BLESSING_SCENE_IDS, builtInScenes, WISH_SCENE_IDS } from '../packages/core/src/daily-scenes.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
export const locales = ['zh-Hans', 'zh-Hant', 'en', 'ja', 'ko', 'es', 'pt', 'fr'];
const read = relative => JSON.parse(readFileSync(path.join(root, relative), 'utf8'));
const xml = value => value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", "\\'");
export function widgetLocalizationOutputs({ nativeOnly = false } = {}) {
  const native = Object.fromEntries(locales.map(locale => [locale, read(`packages/i18n/src/catalogs/${locale}/native.json`)]));
  const source = nativeOnly ? {} : read('packages/i18n/src/scene-source.json');
  const titles = Object.fromEntries(locales.map(locale => {
    const catalog = nativeOnly ? {} : read(`packages/i18n/src/catalogs/${locale}/scenes.json`);
    return [locale, Object.fromEntries(nativeOnly ? [] : builtInScenes.map(scene => {
      const id = source[scene.title], value = catalog[id];
      if (!id || typeof value !== 'string' || !value.trim()) throw Error(`Missing widget title ${locale}/${scene.id}: ${id}`);
      return [scene.id, value];
    }))];
  }));
  const copyRevision = createHash('sha256').update(JSON.stringify({ native, titles })).digest('hex').slice(0, 16);
  const copy = { copyRevision, native, titles };
  const outputs = new Map();
  outputs.set('apps/mobile-expo/widget-copy.generated.json', JSON.stringify(copy, null, 2) + '\n');
  outputs.set('apps/mobile-expo/widget-copy.generated.ts', `// Generated by scripts/generate-widget-localization.mjs.\nexport const WIDGET_COPY_REVISION = ${JSON.stringify(copyRevision)};\n`);
  outputs.set('packages/i18n/src/widget-copy-revision.generated.ts', `// Generated by scripts/generate-widget-localization.mjs.\nexport const WIDGET_COPY_REVISION = ${JSON.stringify(copyRevision)};\n`);
  for (const locale of locales) {
    const strings = native[locale];
    outputs.set(`apps/mobile-expo/locales/${locale}.json`, JSON.stringify({
      ios: { CFBundleDisplayName: strings['native.app.name'], CFBundleName: strings['native.app.name'] },
      android: { app_name: strings['native.app.name'] },
    }, null, 2) + '\n');
    const qualifier = `b+${locale.replaceAll('-', '+')}`;
    outputs.set(`apps/mobile-expo/modules/blessing-widgets/android/src/main/res/values-${qualifier}/strings.xml`, `<resources>\n${[
      ['blessing_widget_name', 'native.widget.name'], ['blessing_widget_description', 'native.widget.resizeDescription'],
      ['blessing_widget_generic_title', 'native.widget.invitation'],
    ].map(([id, key]) => `  <string name="${id}">${xml(strings[key])}</string>`).join('\n')}\n</resources>\n`);
  }
  const quote = value => JSON.stringify(value).replaceAll('$', '\\$');
  const maps = values => `mapOf(${Object.entries(values).map(([key, value]) => `${quote(key)} to ${quote(value)}`).join(', ')})`;
  outputs.set('apps/mobile-expo/modules/blessing-widgets/android/src/main/java/com/helio/blessingwidgets/WidgetLocalization.kt', `package com.helio.blessingwidgets

// Generated from the bundled, public localization catalogs. No personal text.
internal object WidgetLocalization {
  const val COPY_REVISION = ${quote(copyRevision)}
  val supported = setOf(${locales.map(quote).join(', ')})
  private val copy = mapOf(${locales.map(locale => `${quote(locale)} to ${maps(native[locale])}`).join(',\n    ')})
  private val titles: Map<String, Map<String, String>> = mapOf(${locales.map(locale => `${quote(locale)} to ${maps(titles[locale])}`).join(',\n    ')})

  fun resolve(preference: String, tags: List<String>): String {
    if (preference in supported) return preference
    for (tag in tags) {
      if (!tag.matches(Regex("[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*"))) continue
      val parts = tag.lowercase(java.util.Locale.ROOT).split('-')
      if (parts[0] == "zh") {
        val script = parts.firstOrNull { it == "hans" || it == "hant" }
        return if (script == "hant" || (script == null && parts.any { it in setOf("tw", "hk", "mo") })) "zh-Hant" else "zh-Hans"
      }
      if (parts[0] in supported) return parts[0]
    }
    return "en"
  }
  fun text(locale: String, key: String): String = copy[locale]?.get(key) ?: copy.getValue("en").getValue(key)
  fun formatTag(preference: String, tags: List<String>): String {
    if (preference in supported) return preference
    return tags.firstOrNull { tag ->
      tag.matches(Regex("[A-Za-z]{2,3}(-[A-Za-z0-9]{2,8})*")) &&
        (tag.substringBefore('-').lowercase(java.util.Locale.ROOT).let { it == "zh" || it in supported })
    } ?: "en"
  }
  fun title(locale: String, id: String?): String = titles[locale]?.get(id) ?: text(locale, "native.widget.name")
  fun accessibility(locale: String, date: String, title: String): String = text(locale, "native.widget.accessibility").replace("{date}", date).replace("{title}", title)
  private val blessingIds = listOf(${BLESSING_SCENE_IDS.filter(id => !APP_HIDDEN_SCENE_IDS.includes(id)).map(quote).join(', ')})
  private val wishIds = listOf(${WISH_SCENE_IDS.filter(id => !APP_HIDDEN_SCENE_IDS.includes(id)).map(quote).join(', ')})
  fun dailyScene(day: String, excluded: List<String> = emptyList()): String? {
    val blessings = blessingIds.filterNot { it in excluded }
    val wishes = wishIds.filterNot { it in excluded }
    val pool = (0 until maxOf(blessings.size, wishes.size)).flatMap { listOfNotNull(blessings.getOrNull(it), wishes.getOrNull(it)) }
    if (pool.isEmpty()) return null
    val ordinal = Math.floorDiv(WidgetDates.parseDay(day)?.time ?: return null, 86400000L)
    return pool[Math.floorMod(ordinal, pool.size.toLong()).toInt()]
  }
}
`);
  {
    const renderer = readFileSync(path.join(root, 'apps/mobile-expo/widgets/TodayWidget.tsx'), 'utf8');
    if (!renderer.includes('// BEGIN GENERATED WIDGET COPY')) throw Error('Widget renderer copy marker missing');
    outputs.set('apps/mobile-expo/widgets/TodayWidget.tsx', renderer.replace(/\/\/ BEGIN GENERATED WIDGET COPY[\s\S]*?\/\/ END GENERATED WIDGET COPY/, () => `// BEGIN GENERATED WIDGET COPY\n  const copy = ${JSON.stringify(copy)};\n  // END GENERATED WIDGET COPY`));
  }
  return outputs;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outputs = widgetLocalizationOutputs({ nativeOnly: process.argv.includes('--native-only') });
  for (const [relative, contents] of outputs) {
    const file = path.join(root, relative);
    if (process.argv.includes('--check')) {
      if (readFileSync(file, 'utf8') !== contents) throw Error(`Generated widget localization drift: ${relative}`);
    } else { mkdirSync(path.dirname(file), { recursive: true }); writeFileSync(file, contents); }
  }
  console.log(`Widget localization ${process.argv.includes('--check') ? 'checked' : 'generated'}: ${outputs.size} files`);
}
