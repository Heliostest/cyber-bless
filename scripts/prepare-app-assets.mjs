const metroBinaryExtensions = new Set(['woff2', 'wav', 'glb', 'hdr']);
/** Image bytes must bypass Android drawable transforms; documents must be assets. */
function nativeModulePath(file) {
  return metroBinaryExtensions.has(path.extname(file).slice(1))
    ? `../../assets/${file}`
    : `./public/${file}.bin`;
}

async function writeIfChanged(file, source) {
  if (await readFile(file, 'utf8').catch(() => '') !== source) await writeFile(file, source);
}

async function generateNativeAssetRegistry(assets) {
  const header = '// Generated by scripts/prepare-app-assets.mjs. Do not edit.\n';
  await writeIfChanged(path.join(root, 'packages/scene-runtime/src/asset-paths.generated.ts'),
    `${header}export const bundledAssetPaths = ${JSON.stringify(assets.map(({ file }) => file), null, 2)} as const;\n`);
  const registrations = assets.map(({ file, bytes, md5 }) =>
    `  ${JSON.stringify(file)}: { module: require(${JSON.stringify(nativeModulePath(file))}), bytes: ${bytes}, md5: ${JSON.stringify(md5)} },`);
  await writeIfChanged(path.join(root, 'apps/mobile-expo/bundled-assets.generated.ts'),
    `${header}// Literal require calls make every payload part of the native Metro/Updates graph.\nexport const bundledAssetModules: Record<string, { module: number; bytes: number; md5: string }> = {\n${registrations.join('\n')}\n};\n`);
}

export async function prepareAppAssets() {
  await prepareBundledContent();
  const assets = [];
  const destinations = ["apps/mobile-expo/public", "apps/cyber-bless/public"];
  // Both directories contain generated output only, never authoring inputs.
  for (const relative of destinations) {
    const target = path.resolve(root, relative);
    if (path.relative(root, target) !== path.normalize(relative))
      throw Error("Unsafe generated path");
    await rm(target, { recursive: true, force: true });
  }
  for (const file of assetFiles) {
    const source = path.join(root, "assets", file);
    for (const target of destinations) {
      const destination = path.join(root, target, file);
      await mkdir(path.dirname(destination), { recursive: true });
      await copyFile(source, destination);
    }
    const bytes = await readFile(source);
    if (!metroBinaryExtensions.has(path.extname(file).slice(1))) {
      // Keep original public paths for the browser and embedded fallback; the
      // byte-identical binary alias keeps DOM images out of Android drawable
      // conversion/PNG crunching and registers documents without changing the
      // global meaning of .json/.txt/.md imports.
      await copyFile(source, path.join(root, 'apps/mobile-expo/public', `${file}.bin`));
    }
    assets.push({
      file,
      bytes: bytes.length,
      sha256: createHash("sha256").update(bytes).digest("hex"),
    });
  }
  await generateNativeAssetRegistry(await Promise.all(assets.map(async asset => ({
    ...asset,
    md5: createHash('md5').update(await readFile(path.join(root, 'assets', asset.file))).digest('hex'),
  }))));
  await generateSceneTestingRevisions();
  for (const target of destinations) {
    await writeFile(path.join(root, target, 'wbr-assets.json'), JSON.stringify(assets, null, 2) + '\n');
  }
  return assets;
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const assets = await prepareAppAssets();
  console.log(`Prepared ${assets.length} local image/font/license assets.`);
}
