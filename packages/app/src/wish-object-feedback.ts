/** Independent animation data; no contexts, DOM, motion or sound are started here. */
export function wishObjectFeedback(sceneId: string): WishObjectFeedback {
  const [sound, motion] = Object.hasOwn(objects, sceneId) ? objects[sceneId] : ['air', 'quiet'] as const
  const spec: { duration: number; origin: string; transforms: string[]; filters?: string[] } = motions[motion]
  return {
    sound,
    motion: spec.transforms.map((transform, index) => ({ transform, transformOrigin: spec.origin,
      ...(spec.filters ? { filter: spec.filters[index] } : {}) })),
    timing: { duration: spec.duration, easing: 'ease-out', iterations: 1 },
  }
}
