import { mkdir, writeFile, copyFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createServer } from 'vite';
import sharp from 'sharp';
import { chromium } from 'playwright';
import { APP_HIDDEN_SCENE_IDS, builtInScenes, WISH_SCENE_IDS } from '../packages/core/src/daily-scenes.ts';
import { prepareAppAssets } from './prepare-app-assets.mjs';
import { widgetLocalizationOutputs } from './generate-widget-localization.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const output = path.join(root, 'assets/widgets/today');
const android = path.join(root, 'apps/mobile-expo/modules/blessing-widgets/android/src/main/res/drawable-nodpi');
await prepareAppAssets();
await Promise.all([mkdir(output, { recursive: true }), mkdir(android, { recursive: true })]);
const server = await createServer({ configFile: false, root: path.join(root, 'scripts/widget-preview'),
  publicDir: path.join(root, 'apps/cyber-bless/public'),
  define: { 'process.env.EXPO_BASE_URL': JSON.stringify('/') },
  server: { host: '127.0.0.1', port: 0, fs: { allow: [root] } }, logLevel: 'warn' });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ ...(process.env.WBR_CHROME ? { executablePath: process.env.WBR_CHROME } : {}),
    headless: true, args: process.env.WBR_WIDGET_GPU === '1' ? ['--use-angle=d3d11'] : ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
  const origin = server.resolvedUrls.local[0];
  const scenes = new Array(builtInScenes.length);
  let nextScene = 0;
  // Two isolated pages keep a growing catalog practical; retain catalog order in the manifest.
  await Promise.all(Array.from({ length: 2 }, async () => {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    await page.addInitScript(() => { let seed = 42; Math.random = () => ((seed = (1664525 * seed + 1013904223) >>> 0) / 4294967296); });
    while (nextScene < builtInScenes.length) {
      const index = nextScene++;
      const scene = builtInScenes[index];
      const record = { id: scene.id, engine: scene.engine };
      for (const [size, width, height] of [['small', 600, 600], ['medium', 1280, 600], ['large', 1200, 1200]]) {
        await page.setViewportSize({ width, height });
        await page.goto(`${origin}?scene=${scene.id}&width=${width}&height=${height}`, { waitUntil: 'networkidle' });
        await page.waitForFunction(() => window.__widgetReady || window.__widgetError, { timeout: 30_000 });
        const error = await page.evaluate(() => window.__widgetError);
        if (error) throw Error(`${scene.id}: ${error}`);
        // Renderer ready + next frames cover asynchronous model/texture upload.
        await page.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
        const evidence = await page.evaluate(() => window.__widgetCapture());
        const bytes = await sharp(await page.locator('#stage').screenshot()).png({ compressionLevel: 9 }).toBuffer();
        const file = `${scene.id}-${size}.png`;
        await writeFile(path.join(output, file), bytes);
        await writeFile(path.join(android, `blessing_preview_${scene.id.replaceAll('-', '_')}_${size}.png`), bytes);
        record[size] = { file, width, height, sha256: createHash('sha256').update(bytes).digest('hex'), ...evidence };
        console.log(`${scene.id}/${size}: real WebGL2, ${bytes.length} bytes`);
      }
      scenes[index] = record;
    }
    await page.close();
  }));
  // Generic gallery/expired entry uses a public woodfish cover, never personal state.
  for (const size of ['small', 'medium', 'large']) {
    await copyFile(path.join(output, `woodfish-${size}.png`), path.join(output, `generic-${size}.png`));
    await copyFile(path.join(output, `generic-${size}.png`), path.join(android, `blessing_preview_generic_${size}.png`));
  }
  const revision = createHash('sha256').update(JSON.stringify(scenes)).digest('hex');
  await writeFile(path.join(output, 'manifest.json'), JSON.stringify({ renderer: 'project-threejs-scenes', revision, scenes }, null, 2) + '\n');
  // Native allowlists and asset imports must track the same catalog as the rendered covers.
  const ids = [...builtInScenes.map(scene => scene.id), 'generic'];
  const sizes = ['small', 'medium', 'large'];
  await writeFile(path.join(root, 'apps/mobile-expo/widget-preview-assets.ts'),
    `// Generated by scripts/render-widget-previews.mjs from the bundled scene catalog.\nexport const widgetPreviewAssets: Record<string, { small: number; medium: number; large: number }> = {\n` +
    ids.map(id => `  '${id}': { ${sizes.map(size => `${size}: require('../../assets/widgets/today/${id}-${size}.png')`).join(', ')} },`).join('\n') + '\n};\n');
  const quote = value => JSON.stringify(value).replaceAll('$', '\\$');
  const resource = (id, size) => `R.drawable.blessing_preview_${id.replaceAll('-', '_')}_${size}`;
  await writeFile(path.join(root, 'apps/mobile-expo/modules/blessing-widgets/android/src/main/java/com/helio/blessingwidgets/WidgetCatalog.kt'),
    `package com.helio.blessingwidgets\n\n// Generated by scripts/render-widget-previews.mjs; only public bundled metadata.\ninternal object WidgetCatalog {\n  val hiddenSceneIds = setOf(${APP_HIDDEN_SCENE_IDS.map(quote).join(', ')})\n  val scenes = mapOf(\n` +
    builtInScenes.map(scene => `    ${quote(scene.id)} to WidgetScene(${quote(scene.title)}, "${WISH_SCENE_IDS.includes(scene.id) ? 'wish' : 'blessing'}"),`).join('\n') +
    `\n  )\n\n  fun cover(key: String?, size: WidgetCoverSize): Int {\n    val covers = when (key) {\n` +
    builtInScenes.map(scene => `      ${quote(scene.id)} -> intArrayOf(${sizes.map(size => resource(scene.id, size)).join(', ')})`).join('\n') +
    `\n      else -> intArrayOf(${sizes.map(size => resource('generic', size)).join(', ')})\n    }\n    return covers[size.ordinal]\n  }\n}\n`);
  const testResources = path.join(root, 'apps/mobile-expo/modules/blessing-widgets/android/src/test/resources');
  await mkdir(testResources, { recursive: true });
  await writeFile(path.join(testResources, 'widget-catalog.json'), JSON.stringify(builtInScenes.map(scene => ({
    id: scene.id, title: scene.title, category: WISH_SCENE_IDS.includes(scene.id) ? 'wish' : 'blessing',
  })), null, 2) + '\n');
  for (const [relative, contents] of widgetLocalizationOutputs()) {
    const file = path.join(root, relative);
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, contents);
  }
} finally {
  await browser?.close();
  await server.close();
}
