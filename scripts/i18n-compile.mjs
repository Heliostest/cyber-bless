import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';
import { parse } from '@formatjs/icu-messageformat-parser';
import { messageArguments } from './i18n-catalogs.mjs';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'packages/i18n/src');
const locales = ['zh-Hans','zh-Hant','en','ja','ko','es','pt','fr'];
const data = Object.fromEntries(locales.map(locale => [locale, {}]));
const scratch = path.join(root, '.superpowers/sdd/2026-10-27-i18n/compiled');
await mkdir(scratch, { recursive: true });
for (const locale of locales) {
  const dir = path.join(source, 'catalogs', locale);
  await mkdir(dir, { recursive: true });
  for (const name of (await readdir(dir)).filter(name => name.endsWith('.json')).sort()) {
    const entries = JSON.parse(await readFile(path.join(dir, name), 'utf8'));
    for (const [id, text] of Object.entries(entries)) {
      if (id in data[locale] && data[locale][id] !== text) throw Error(`Conflicting ${locale} message ${id}`);
      data[locale][id] = text;
    }
  }
}
// Use the installed FormatJS compiler rather than parsing ICU on first use on a phone.
const compiled = {};
for (const locale of locales) {
  const input=path.join(scratch,`${locale}-input.json`),output=path.join(scratch,`${locale}.json`);
  await writeFile(input,JSON.stringify(data[locale]));
  const result=spawnSync(process.execPath,[path.join(root,'node_modules/@formatjs/cli/bin/formatjs'),'compile',input,'--format','simple','--ast','--out-file',output],{encoding:'utf8',windowsHide:true});
  if(result.error||result.status!==0)throw Error(`FormatJS ${locale} compilation failed: ${result.error??result.stderr}`);
  compiled[locale]=JSON.parse(await readFile(output,'utf8'));
  if(Object.keys(compiled[locale]).length!==Object.keys(data[locale]).length)throw Error(`FormatJS ${locale} silently omitted messages`);
}
const index = {};
let sceneSourceIndex = {};
for (const name of (await readdir(source)).filter(name => name.endsWith('-source.json')).sort()) {
  const entries = JSON.parse(await readFile(path.join(source, name), 'utf8'));
  if(name === 'scene-source.json') sceneSourceIndex = entries;
  for (const [text, id] of Object.entries(entries)) if (!(text in index)) index[text] = id;
}
const outputs = [
  ['message-types.generated.ts', '// Generated by scripts/i18n-compile.mjs. Do not edit.\nexport interface MessageArguments {\n'+Object.entries(data['zh-Hans']).map(([id,text])=>{
    const {args}=messageArguments(parse(text));
    return `  ${JSON.stringify(id)}: { ${[...args].map(([name,kind])=>`${JSON.stringify(name)}: ${kind==='number'?'number':kind==='date'?'Date | number':'string | number | boolean | Date | null | undefined'}`).join('; ')} };`;
  }).join('\n')+'\n}\nexport type MessageId = keyof MessageArguments;\n'],
  ['catalog-data.ts', '// Generated by scripts/i18n-compile.mjs. Do not edit.\nimport type { MessageFormatElement } from "@formatjs/icu-messageformat-parser";\nexport type CatalogMessage = string | MessageFormatElement[];\nexport type CatalogMessages = Record<string, string> | Record<string, MessageFormatElement[]>;\nexport const catalogData: Record<string, Record<string, MessageFormatElement[]>> = '+JSON.stringify(compiled)+';\nexport const sourceIndex: Record<string, string> = '+JSON.stringify(index)+';\nexport const sceneSourceIndex: Record<string, string> = '+JSON.stringify(sceneSourceIndex)+';\n'],
  ['source-index.generated.ts','// Generated by scripts/i18n-compile.mjs.\nexport const sourceIndex: Record<string, string> = '+JSON.stringify(index,null,2)+';\n'],
];
for(const[name,output]of outputs){
  const file=path.join(source,name);
  if(process.argv.includes('--check')){if(await readFile(file,'utf8')!==output)throw Error(`${name} is stale; run npm run i18n:compile`);}
  else await writeFile(file,output);
}
if(process.argv.includes('--pseudo')){
  const outputDir=path.join(root,'artifacts/i18n');await mkdir(outputDir,{recursive:true});
  const result=spawnSync(process.execPath,[path.join(root,'node_modules/@formatjs/cli/bin/formatjs'),'compile',path.join(scratch,'en-input.json'),'--format','simple','--ast','--pseudo-locale','en-XA','--out-file',path.join(outputDir,'pseudo-en-XA.json')],{encoding:'utf8',windowsHide:true});
  if(result.error||result.status!==0)throw Error(`Pseudo compilation failed: ${result.error??result.stderr}`);
}
console.log(`i18n: compiled ${Object.keys(index).length} source messages in ${locales.length} locale bundles`);
