import { describe, it, expect, vi } from "vitest";
import * as THREE from "three";
import { createToonSurfaces } from "./toon-surfaces";
import { calibrateIconPigment } from './icon-style';

describe("official toon material adaptation", () => {
  it('calibrates only untextured subject pigment and keeps animated source colors live', () => {
    const scene = new THREE.Scene(), source = new THREE.MeshStandardMaterial({color:0xb78b59}), subject = new THREE.Mesh(new THREE.BoxGeometry(),source);
    const environment=new THREE.Group(); environment.name='cozy-environment'; const tree=new THREE.Mesh(new THREE.BoxGeometry(),source); environment.add(tree);
    const map=new THREE.Texture(), printedSource=new THREE.MeshStandardMaterial({color:0xb78b59,map}), printed=new THREE.Mesh(new THREE.BoxGeometry(),printedSource);
    const vertexSource=new THREE.MeshStandardMaterial({color:0xb78b59,vertexColors:true}), vertex=new THREE.Mesh(new THREE.BoxGeometry(),vertexSource); scene.add(subject,environment,printed,vertex);
    const surfaces=createToonSurfaces('toon-soft','woodfish'), expected=new THREE.Color(); calibrateIconPigment(expected,source.color,'woodfish');
    let frame=surfaces.apply(scene); expect((subject.material as THREE.MeshStandardMaterial).color.equals(expected)).toBe(true);
    expect((tree.material as THREE.MeshStandardMaterial).color.equals(source.color)).toBe(true); expect((printed.material as THREE.MeshStandardMaterial).color.equals(printedSource.color)).toBe(true); expect((vertex.material as THREE.MeshStandardMaterial).color.equals(vertexSource.color)).toBe(true); frame.restore();
    source.color.set(0x4a8862); frame=surfaces.apply(scene); calibrateIconPigment(expected,source.color,'woodfish'); expect((subject.material as THREE.MeshStandardMaterial).color.equals(expected)).toBe(true); frame.restore(); surfaces.dispose();
  });
  it('retains live normal/roughness maps, finish and normal strength in soft rendering', () => {
    const source = new THREE.MeshStandardMaterial({ roughness: .8 }), scene = new THREE.Scene(), mesh = new THREE.Mesh(new THREE.BoxGeometry(), source); scene.add(mesh);
    const surfaces = createToonSurfaces('toon-soft'); surfaces.apply(scene).restore();
    const normal = new THREE.Texture(), roughness = new THREE.Texture(); source.normalMap = normal; source.roughnessMap = roughness; source.normalScale.set(.3,.4); source.roughness = .63;
    const frame = surfaces.apply(scene), styled = mesh.material as THREE.MeshStandardMaterial;
    expect(styled).toBeInstanceOf(THREE.MeshStandardMaterial); expect(styled.normalMap).toBe(normal); expect(styled.roughnessMap).toBe(roughness);
    expect(styled.normalScale.toArray()).toEqual([.3,.4]); expect(styled.roughness).toBe(.63);
    frame.restore(); surfaces.dispose(); expect(mesh.material).toBe(source);
  });
  it('retains transparent glass depth/optics and follows live physical parameters', () => {
    const source = new THREE.MeshPhysicalMaterial({ transparent:true, transmission:.76, thickness:.035, depthWrite:false, clearcoat:.4 }); source.userData.ritualOptics={kind:'glass'};
    const scene = new THREE.Scene(), mesh = new THREE.Mesh(new THREE.SphereGeometry(), source); scene.add(mesh); const surfaces = createToonSurfaces('toon-soft');
    let frame = surfaces.apply(scene); expect(mesh.material).not.toBe(source); expect((mesh.material as THREE.Material).customProgramCacheKey()).toContain('icon-glass-rim'); expect(frame.outlined).not.toContain(mesh); frame.restore();
    source.transmission=.85; source.clearcoat=.6; source.attenuationDistance=1.7;
    frame=surfaces.apply(scene); const styled=mesh.material as THREE.MeshPhysicalMaterial;
    expect(styled.transmission).toBe(.85); expect(styled.clearcoat).toBe(.6); expect(styled.attenuationDistance).toBe(1.7); expect(styled.transparent).toBe(true); expect(styled.depthWrite).toBe(false);
    frame.restore(); surfaces.dispose(); expect(source.transmission).toBe(.85);
  });
  it('detects in-place material-array changes and releases partially built replacements on failure', () => {
    const first = new THREE.MeshStandardMaterial({metalness:.6}), second = new THREE.MeshPhysicalMaterial();
    const sources = [first], scene = new THREE.Scene(), mesh = new THREE.Mesh(new THREE.BoxGeometry(), sources); scene.add(mesh);
    const surfaces = createToonSurfaces('toon-soft'), frame = surfaces.apply(scene), firstClone = (mesh.material as THREE.Material[])[0], released=vi.fn(); firstClone.addEventListener('dispose',released); frame.restore();
    sources[0]=second; surfaces.apply(scene).restore(); expect(released).toHaveBeenCalledTimes(1);
    surfaces.dispose();
    const adapter=createToonSurfaces('toon-soft'), fail = new THREE.MeshPhysicalMaterial(); vi.spyOn(fail,'clone').mockImplementation(()=>{throw Error('clone failure')});
    const clone=first.clone(), cleanup=vi.fn(); clone.addEventListener('dispose',cleanup); vi.spyOn(first,'clone').mockReturnValue(clone);
    mesh.material=[first,fail]; expect(()=>adapter.apply(scene)).toThrow('clone failure'); expect(cleanup).toHaveBeenCalledTimes(1); expect(mesh.material).toEqual([first,fail]); adapter.dispose();
  });
  it("updates outline shade counts while retaining the cached material, texture identity and authored map", () => {
    const map = new THREE.Texture(), source = new THREE.MeshStandardMaterial({ map, roughness: .8 });
    const mesh = new THREE.Mesh(new THREE.SphereGeometry(), source), scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces("toon-outline"), first = surfaces.apply(scene);
    const painted = mesh.material as THREE.MeshToonMaterial, gradient = painted.gradientMap!;
    first.restore();
    surfaces.setColorLevels(6);
    const next = surfaces.apply(scene);
    expect(mesh.material).toBe(painted); expect(painted.gradientMap).toBe(gradient);
    expect(gradient.image.width).toBe(6); expect(new Set(gradient.image.data).size).toBe(6);
    expect(painted.map).toBe(map);
    next.restore(); surfaces.setColorLevels(3);
    expect([...gradient.image.data]).toEqual([55, 145, 245]);
    expect(mesh.material).toBe(source); surfaces.dispose(); source.dispose(); map.dispose(); mesh.geometry.dispose();
  });
  it("uses three crisp shade bands in cartoon outlines while retaining the authored map", () => {
    const map = new THREE.Texture();
    const original = new THREE.MeshStandardMaterial({ color: 0xbd5e4d, roughness: .8, map });
    const mesh = new THREE.Mesh(new THREE.SphereGeometry(), original);
    const scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces("toon-outline"), frame = surfaces.apply(scene);
    const painted = mesh.material as THREE.MeshToonMaterial;
    expect(painted.isMeshToonMaterial).toBe(true);
    expect(painted.gradientMap!.image.width).toBe(3);
    expect(painted.gradientMap!.magFilter).toBe(THREE.NearestFilter);
    expect(painted.map).toBe(map);
    frame.restore(); surfaces.dispose();
    expect(mesh.material).toBe(original);
  });
  it("keeps painted markings and a continuous matte volume in gouache, with source colors animated intact", () => {
    const map = new THREE.Texture();
    const original = new THREE.MeshStandardMaterial({ color: 0xbd5e4d, map, roughness: 0.8 });
    const mesh = new THREE.Mesh(new THREE.SphereGeometry(), original);
    const scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces("gouache");
    const frame = surfaces.apply(scene);
    const painted = mesh.material as THREE.MeshStandardMaterial;
    expect(painted.isMeshStandardMaterial).toBe(true);
    expect(painted.map).toBe(map);
    expect(painted.roughness).toBeGreaterThan(0.9);
    frame.restore();
    original.color.set(0x416c9b);
    const next = surfaces.apply(scene);
    expect(painted.color.getHex()).toBe(0x416c9b);
    next.restore(); surfaces.dispose();
    expect(mesh.material).toBe(original);
    expect(original.map).toBe(map);
  });
  it.each([true, false])("preserves a glossy nonmetal glaze at the finish boundary (hint: %s)", (hinted) => {
    const original = new THREE.MeshStandardMaterial({ color: 0x416c9b, roughness: hinted ? 0.32 : 0.4, metalness: 0 });
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(), original);
    if (hinted) mesh.userData.toonSurface = { roughness: 0.4 };
    const scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces("toon-soft"), frame = surfaces.apply(scene);
    const finish = mesh.material as THREE.MeshStandardMaterial;
    expect(finish.isMeshStandardMaterial).toBe(true);
    expect(finish.roughness).toBe(0.4);
    expect(finish.metalness).toBe(0);
    frame.restore(); surfaces.dispose();
    expect(mesh.material).toBe(original);
    expect(original.roughness).toBe(hinted ? 0.32 : 0.4);
  });
  it.each(["toon-soft", "gouache", "moebius", "toon-outline"] as const)("keeps clearcoat and authored metal finishes in %s instead of flattening them", style => {
    const original = new THREE.MeshPhysicalMaterial({ color: 0x739daf, roughness: 0.24, metalness: 0.46, clearcoat: 0.8, clearcoatRoughness: 0.13 });
    const mesh = new THREE.Mesh(new THREE.SphereGeometry(), original);
    const scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces(style), frame = surfaces.apply(scene);
    const finish = mesh.material as THREE.MeshPhysicalMaterial;
    expect(finish.isMeshPhysicalMaterial).toBe(true);
    expect(finish.clearcoat).toBe(0.8);
    expect(finish.clearcoatRoughness).toBe(0.13);
    expect(finish.roughness).toBe(0.24);
    expect(finish.metalness).toBe(0.46);
    expect(finish).not.toBe(original);
    frame.restore(); surfaces.dispose();
    expect(mesh.material).toBe(original);
  });
  it("uses continuous soft volume on the subject while leaving the backdrop smooth", () => {
    const scene = new THREE.Scene();
    const subject = new THREE.Mesh(new THREE.SphereGeometry(), new THREE.MeshStandardMaterial({ roughness: 0.8 }));
    const backdrop = new THREE.Mesh(new THREE.PlaneGeometry(), new THREE.MeshStandardMaterial({ roughness: 1 }));
    backdrop.userData.toonSurface = { outline: false, shading: "smooth" };
    scene.add(subject, backdrop);
    const surfaces = createToonSurfaces("toon-soft"), frame = surfaces.apply(scene);
    expect(subject.material).toBeInstanceOf(THREE.MeshStandardMaterial);
    expect((backdrop.material as THREE.MeshStandardMaterial).isMeshStandardMaterial).toBe(true);
    expect(frame.outlined).toEqual([subject]);
    frame.restore(); surfaces.dispose();
  });
  it("keeps an explicit metal finish on a painted charm while preserving its source material", () => {
    const original = new THREE.MeshStandardMaterial({ metalness: 0.55, roughness: 0.35 });
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(), original);
    mesh.userData.toonSurface = { metalness: 0.55, roughness: 0.35 };
    const scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces("toon-soft"), frame = surfaces.apply(scene);
    expect((mesh.material as THREE.MeshStandardMaterial).metalness).toBe(0.55);
    expect((mesh.material as THREE.MeshStandardMaterial).roughness).toBe(0.35);
    frame.restore(); surfaces.dispose();
    expect(mesh.material).toBe(original);
  });
  it("uses simplified painted surfaces only while drawing, without damaging PBR textures", () => {
    const color = new THREE.Texture(), normal = new THREE.Texture(), ao = new THREE.Texture();
    const original = new THREE.MeshStandardMaterial({ map: color, normalMap: normal, aoMap: ao });
    const mesh = new THREE.Mesh(new THREE.BoxGeometry(), original);
    mesh.userData.toonSurface = { color: 0xb98655, simplifyMap: true, aoIntensity: 0.3 };
    const scene = new THREE.Scene(); scene.add(mesh);
    const surfaces = createToonSurfaces("toon-soft");
    const frame = surfaces.apply(scene);
    const toon = mesh.material as THREE.MeshStandardMaterial;
    expect(toon.isMeshStandardMaterial).toBe(true);
    expect(toon.color.getHex()).toBe(0xb98655);
    expect(toon.map).toBeNull();
    expect(toon.normalMap).toBe(normal);
    expect(toon.aoMap).toBe(ao);
    expect(toon.aoMapIntensity).toBe(0.3);
    frame.restore();
    expect(mesh.material).toBe(original);
    expect(original.map).toBe(color);
    expect(original.normalMap).toBe(normal);
    const disposeToon = vi.fn(), disposeOriginal = vi.fn(), disposeMap = vi.fn();
    toon.addEventListener("dispose", disposeToon);
    original.addEventListener("dispose", disposeOriginal);
    color.addEventListener("dispose", disposeMap);
    surfaces.dispose();
    expect(disposeToon).toHaveBeenCalledOnce();
    expect(disposeOriginal).not.toHaveBeenCalled();
    expect(disposeMap).not.toHaveBeenCalled();
  });

  it("leaves water, contact shadows and particles alone, and handles models added after initialization", () => {
    const scene = new THREE.Scene();
    const water = new THREE.Mesh(new THREE.PlaneGeometry(), new THREE.MeshStandardMaterial({ transparent: true, opacity: 0.8 }));
    const shadow = new THREE.Mesh(new THREE.PlaneGeometry(), new THREE.ShadowMaterial());
    const materials = [water.material, shadow.material];
    scene.add(water, shadow);
    const surfaces = createToonSurfaces("toon-ink");
    surfaces.apply(scene).restore();
    const model = new THREE.Mesh(new THREE.BoxGeometry(), new THREE.MeshStandardMaterial({ color: 0xaabbcc }));
    scene.add(model);
    const frame = surfaces.apply(scene);
    expect(frame.outlined).toEqual([model]);
    expect([water.material, shadow.material]).toEqual(materials);
    const toon = model.material;
    frame.restore();
    const disposed = vi.fn(); toon.addEventListener("dispose", disposed);
    scene.remove(model);
    surfaces.apply(scene).restore();
    expect(disposed).toHaveBeenCalledOnce();
    surfaces.dispose();
  });

  it("keeps a surface's depth offset, so ink lines drawn on it stay visible", () => {
    const paper = new THREE.MeshStandardMaterial({ polygonOffset: true, polygonOffsetFactor: 1, polygonOffsetUnits: 2 });
    const scene = new THREE.Scene(); scene.add(new THREE.Mesh(new THREE.PlaneGeometry(), paper));
    const surfaces = createToonSurfaces("toon-ink");
    const frame = surfaces.apply(scene);
    const toon = frame.outlined[0].material as THREE.MeshToonMaterial;
    expect([toon.polygonOffset, toon.polygonOffsetFactor, toon.polygonOffsetUnits]).toEqual([true, 1, 2]);
    frame.restore();
    surfaces.dispose();
  });

  it("keeps backdrops cel-shaded but unselected for ink, and follows animated glow", () => {
    const scene = new THREE.Scene();
    const ground = new THREE.Mesh(new THREE.PlaneGeometry(), new THREE.MeshStandardMaterial({ color: 0xe6d6bd }));
    ground.userData.toonSurface = { outline: false };
    const glowMaterial = new THREE.MeshStandardMaterial({ color: 0xf2a3b3, emissive: 0xffa060, emissiveIntensity: 0.35 });
    const lantern = new THREE.Mesh(new THREE.BoxGeometry(), glowMaterial);
    scene.add(ground, lantern);
    const surfaces = createToonSurfaces("toon-ink");
    let frame = surfaces.apply(scene);
    expect((ground.material as THREE.Material).type).toBe("MeshToonMaterial");
    expect(frame.outlined).toEqual([lantern]);
    frame.restore();
    glowMaterial.emissiveIntensity = 0.9;
    glowMaterial.opacity = 0.5;
    frame = surfaces.apply(scene);
    const toon = lantern.material as unknown as THREE.MeshToonMaterial;
    expect(toon.emissiveIntensity).toBe(0.9);
    expect(toon.opacity).toBe(0.5);
    expect(toon.emissive.getHex()).toBe(0xffa060);
    frame.restore();
    expect(lantern.material).toBe(glowMaterial);
    surfaces.dispose();
  });
});
